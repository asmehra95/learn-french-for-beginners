"""Unit tests for generate.site_manifest_js (no model, no I/O): the default voice keeps the historical
js/tts-manifest.js format byte for byte; another voice registers into window.VT_TTS_VOICES.
Run: python -m unittest -v test_manifest_js"""
import json
import unittest

import generate


def sample_doc(voice_id):
    return {
        "version": 1, "normalization": "v1", "defaultVoice": voice_id,
        "voices": {voice_id: {"id": voice_id, "label": "Label", "model": "M", "license": "Apache-2.0",
                              "licenseUrl": "u", "modelUrl": "m", "synthetic": True, "note": "Voix « posée »",
                              "credits": f"audio/tts/{voice_id}/CREDITS.md", "generatedAt": "2026-01-01T00:00:00+00:00"}},
        "coverage": {"total": 2, "recorded": 1, "byCategory": {"dialogue-line": {"recorded": 1, "total": 2}}},
        "items": {"ça va": {"file": f"audio/tts/{voice_id}/0123456789abcdef.mp3", "voiceId": voice_id, "duration": 1.23}},
    }


def legacy_writer(doc):
    """The writer body before the multi-voice change (generate.py at 35ad97f)."""
    body = json.dumps(doc, ensure_ascii=False, indent=1)
    return ("/* Generated by tts-tools/generate.py. Do not edit by hand.\n"
            "   Pre-recorded \"Recorded voice\" clips: normalized text (VT_LOGIC.ttsKey, rule v1) -> { file, voiceId, duration }.\n"
            "   Text without an entry is spoken by the device voice. */\n"
            "window.VT_TTS = " + body + ";\n")


class SiteManifestJs(unittest.TestCase):
    def test_default_voice_is_byte_identical(self):
        doc = sample_doc("qwen3-fr-bf16")
        self.assertEqual(generate.site_manifest_js("qwen3-fr-bf16", doc, True), legacy_writer(doc))

    def test_extra_voice_registers_into_vt_tts_voices(self):
        vid = "qwen3-fr-m-bf16"
        js = generate.site_manifest_js(vid, sample_doc(vid), False)
        self.assertIn("window.VT_TTS_VOICES = window.VT_TTS_VOICES || {};\n", js)
        self.assertIn('window.VT_TTS_VOICES["qwen3-fr-m-bf16"] = {', js)
        self.assertNotIn("window.VT_TTS =", js)
        body = js.split('window.VT_TTS_VOICES["qwen3-fr-m-bf16"] = ', 1)[1].rstrip().rstrip(";")
        parsed = json.loads(body)
        self.assertEqual(parsed["voice"]["id"], vid)
        self.assertNotIn("defaultVoice", parsed)
        self.assertNotIn("voices", parsed)
        self.assertEqual(sorted(parsed), ["coverage", "items", "normalization", "version", "voice"])

    def test_voice_id_is_json_encoded(self):
        vid = 'odd"id'
        doc = sample_doc(vid)
        js = generate.site_manifest_js(vid, doc, False)
        self.assertIn('window.VT_TTS_VOICES["odd\\"id"] = ', js)

    def test_paths_and_corpus_per_voice(self):
        self.assertTrue(generate.site_manifest_path("qwen3-fr-bf16").endswith("js/tts-manifest.js"))
        self.assertTrue(generate.site_manifest_path("qwen3-fr-m-bf16").endswith("js/tts-manifest-qwen3-fr-m-bf16.js"))
        self.assertTrue(generate.default_corpus("qwen3-fr-bf16").endswith("corpus.json"))
        self.assertTrue(generate.default_corpus("qwen3-fr-m-bf16").endswith("corpus-qwen3-fr-m-bf16.json"))
        self.assertEqual(generate.default_voice(), "qwen3-fr-bf16")


if __name__ == "__main__":
    unittest.main()
